#!/usr/bin/env python3
"""
theme-engine.py: Central Theme Engine for Void Linux + MangoWC rice.
Compiles and applies theme tokens across:
- Waybar (CSS & JSON)
- Rofi (RASI)
- Foot (INI)
- Mako (config)
- MangoWC (config.conf)
- GTK 3 & 4 (gtk.css)
- btop (wm.theme)
- Fastfetch (config.jsonc)
Dispatches live reloads for zero-restart theme transitions.
"""
