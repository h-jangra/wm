def broadcast_term_colors(t):
    """Broadcast OSC color sequences to open PTY terminals."""
    bg = t.get('background', '#2e3440')
    fg = t.get('foreground', '#d8dee9')
    # OSC 10: set foreground, OSC 11: set background
    osc_seq = f"\033]10;{fg}\007\033]11;{bg}\007"
    for pt in glob.glob("/dev/pts/[0-9]*"):
        try:
            # Only write if user has write access
            if os.access(pt, os.W_OK):
                with open(pt, "w", errors="ignore") as f:
                    f.write(osc_seq)
        except Exception:
            pass

def reload_subsystems():
    """Live reload compositor, bar, and notification daemon without session restart."""
    # 1. Waybar
    subprocess.run(["pkill", "-USR2", "waybar"], stderr=subprocess.DEVNULL)

    # 2. Mako
    subprocess.run(["makoctl", "reload"], stderr=subprocess.DEVNULL)

    # 3. MangoWC
    subprocess.run(["mmsg", "dispatch", "reload_config"], stderr=subprocess.DEVNULL)

def apply_theme(theme_id, set_wallpaper=True):
    theme = load_theme(theme_id)

    # 1. Waybar CSS & JSON
    with open(os.path.join(THEMES_DIR, "palette.css"), "w") as f:
        f.write(generate_waybar_css(theme))
    with open(os.path.join(THEMES_DIR, "palette.json"), "w") as f:
        json.dump(theme, f, indent=2)
    with open(os.path.join(CACHE_DIR, "wm-palette.json"), "w") as f:
        json.dump(theme, f, indent=2)

    # 2. Rofi RASI
    rofi_rasi = generate_rofi_rasi(theme)
    with open(os.path.join(THEMES_DIR, "palette.rasi"), "w") as f:
        f.write(rofi_rasi)
    with open(os.path.join(REPO_DIR, "rofi", "colors.rasi"), "w") as f:
        f.write(rofi_rasi)

    # 3. Foot INI
    with open(os.path.join(THEMES_DIR, "foot.ini"), "w") as f:
        f.write(generate_foot_ini(theme))

    # 4. Mako Config
    with open(MAKO_CONF, "w") as f:
        f.write(generate_mako_conf(theme))

    # 5. Shell Environment
    with open(os.path.join(THEMES_DIR, "palette.env"), "w") as f:
        f.write(generate_shell_env(theme))

    # 6. MangoWC Configuration
    update_mango_conf(theme)

    # 7. GTK 3 & 4
    update_gtk_css(theme)

    # 8. btop
    update_btop(theme)

    # 9. Fastfetch
    update_fastfetch(theme)

    # 10. Update state tracking
    with open(os.path.join(THEMES_DIR, "current"), "w") as f:
        f.write(f"{theme_id}\n")
    mode = "dynamic" if theme_id == "dynamic" else "static"
    with open(os.path.join(THEMES_DIR, "current_mode"), "w") as f:
        f.write(f"{mode}\n")

    # 11. Optionally switch wallpaper if defined and requested
    if set_wallpaper and theme_id != "dynamic":
        wp_name = theme.get("wallpaper")
        if wp_name:
            wp_path = os.path.join(REPO_DIR, "wallpapers", wp_name)
            if os.path.isfile(wp_path):
                wp_manager = os.path.join(SCRIPT_DIR, "wallpaper-manager")
                if os.path.isfile(wp_manager) and os.access(wp_manager, os.X_OK):
                    subprocess.run([wp_manager, "set", wp_path, "--skip-theme"], stderr=subprocess.DEVNULL)

    # 12. Broadcast colors to open terminals
    broadcast_term_colors(theme)

    # 13. Live reload services
    reload_subsystems()

    # 14. Notification
    theme_name = theme.get("name", theme_id)
    subprocess.run([
        "notify-send",
        "-h", "string:x-canonical-private-synchronous:wm-theme",
        "Theme Applied",
        f"Active desktop theme: {theme_name}"
    ], stderr=subprocess.DEVNULL)

    print(f"Successfully applied theme: {theme_name} ({theme_id})")

def main():
    if len(sys.argv) < 2:
        print("Usage: theme-engine.py <theme_id> [--no-wallpaper]")
        sys.exit(1)

    theme_id = sys.argv[1].strip()
    set_wp = "--no-wallpaper" not in sys.argv

    try:
        apply_theme(theme_id, set_wallpaper=set_wp)
    except Exception as e:
        print(f"Error applying theme '{theme_id}': {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
