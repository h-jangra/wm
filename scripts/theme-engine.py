def update_mango_conf(t):
    if not os.path.isfile(MANGO_CONF):
        return
    with open(MANGO_CONF, "r") as f:
        conf = f.read()

    bg_argb = to_argb_hex(t.get('background', '#2e3440'), "ff")
    border_argb = to_argb_hex(t.get('border', '#4c566a'), "ff")
    focus_argb = to_argb_hex(t.get('accent', '#88c0d0'), "ff")
    max_argb = to_argb_hex(t.get('accent_alt', t.get('accent', '#81a1c1')), "ff")
    urgent_argb = to_argb_hex(t.get('ws_urgent', '#bf616a'), "ff")
    scratch_argb = to_argb_hex(t.get('capsule_hover', '#3b4252'), "cc")
    global_argb = to_argb_hex(t.get('clock', '#b48ead'), "aa")
    overlay_argb = to_argb_hex(t.get('accent', '#8fbcbb'), "ff")

    color_block = f"""# {t.get('name', 'Theme')} Palette Colors (ARGB)
rootcolor = {bg_argb}
bordercolor = {border_argb}
focuscolor = {focus_argb}
maximizescreencolor = {max_argb}
urgentcolor = {urgent_argb}
scratchpadcolor = {scratch_argb}
globalcolor = {global_argb}
overlaycolor = {overlay_argb}"""

    # Replace block between border_radius and cursor or existing color block
    pattern = r"# .* Palette Colors \(ARGB\)[\s\S]*?overlaycolor = 0x[0-9a-fA-F]+"
    if re.search(pattern, conf):
        new_conf = re.sub(pattern, color_block, conf)
    else:
        # Fallback regex matching individual directives
        pattern2 = r"rootcolor = 0x[0-9a-fA-F]+[\s\S]*?overlaycolor = 0x[0-9a-fA-F]+"
        if re.search(pattern2, conf):
            new_conf = re.sub(pattern2, color_block, conf)
        else:
            return

    with open(MANGO_CONF, "w") as f:
        f.write(new_conf)

