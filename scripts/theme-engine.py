def strip_hash(color_str):
    if color_str and color_str.startswith("#"):
        return color_str[1:]
    return color_str or "000000"

def to_argb_hex(color_str, alpha="ff"):
    h = strip_hash(color_str).lower()
    return f"0x{h}{alpha}"

def load_theme(theme_id):
    if theme_id == "dynamic":
        dyn_file = os.path.join(THEMES_DIR, "dynamic.json")
        if os.path.isfile(dyn_file):
            with open(dyn_file, "r") as f:
                return json.load(f)
        else:
            # Fallback to current palette if dynamic.json does not exist yet
            pal_file = os.path.join(THEMES_DIR, "palette.json")
            if os.path.isfile(pal_file):
                with open(pal_file, "r") as f:
                    return json.load(f)
            raise FileNotFoundError("Dynamic theme palette not found. Run theme-from-wallpaper first.")

    theme_file = os.path.join(DEFS_DIR, f"{theme_id}.json")
    if not os.path.isfile(theme_file):
        raise FileNotFoundError(f"Theme '{theme_id}' not found in {DEFS_DIR}")
    with open(theme_file, "r") as f:
        return json.load(f)

