def generate_foot_ini(t):
    lines = [
        "# -*- conf -*-",
        f"# Foot Terminal Color Palette - {t.get('name', 'Theme')}",
        "# Generated by central theme-engine",
        "",
        "[colors-dark]",
        f"background = {strip_hash(t.get('background', '#2e3440'))}",
        f"foreground = {strip_hash(t.get('foreground', '#d8dee9'))}",
        f"cursor = {strip_hash(t.get('background', '#2e3440'))} {strip_hash(t.get('cursor', t.get('foreground', '#d8dee9')))}",
        f"selection-background = {strip_hash(t.get('selection_bg', t.get('border', '#4c566a')))}",
        f"selection-foreground = {strip_hash(t.get('selection_fg', t.get('foreground', '#eceff4')))}",
        ""
    ]
    for i in range(8):
        k = f"color{i}"
        val = strip_hash(t.get(k, '#000000'))
        lines.append(f"regular{i} = {val}")
    lines.append("")
    for i in range(8, 16):
        k = f"color{i}"
        val = strip_hash(t.get(k, '#ffffff'))
        lines.append(f"bright{i-8} = {val}")
    lines.append("")
    return "\n".join(lines)

